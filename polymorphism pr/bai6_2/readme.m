Quản Lý Các Mảnh Đất
📌 Mô tả bài toán

Một công ty kinh doanh bất động sản sở hữu N mảnh đất. Mỗi mảnh đất có các thông tin chung:

Mã số (ví dụ: MD001)
Đơn giá một m²

Tùy theo hình dạng, mỗi mảnh đất có thêm các thông tin riêng.

Các loại mảnh đất
1. Hình chữ nhật
Diện tích:
Diện tích = dài × rộng
Không được giảm giá.
2. Hình thang
Diện tích:
Diện tích = (đáy lớn + đáy nhỏ) × chiều cao / 2
Được giảm giá 10%.
3. Hình tam giác
Diện tích:
Diện tích = đáy × chiều cao / 2
Được giảm giá 10%.

